@pytest.mark.parametrize("text", [
    "Maroon 5 и «2 Minutes to Midnight».",
    "Blink-182, U2 и Sum 41 подряд.",
    "Queen — «Bicycle Race (1991 Remix)».",
    "Это 5iesta и t9.",
])
def test_number_next_to_latin_is_left_to_the_dictionary(text):
    """«Maroon 5» по-русски — «Марун файв», а не «пять»: число в латинском имени читает
    словарь коллекции (f5_text.cyrillize, фразы вроде «2 minutes to midnight»)."""
    assert N.normalize(text) == text


def test_digit_garbage_does_not_break_the_line():
    """Строка из тысяч цифр — не число: int() отказывается от неё с ValueError (предел
    4300 цифр), и реплика ушла бы в 500 вместо эфира."""
    text = "Код " + "1" * 5000 + "."
    assert N.normalize(text) == text


def test_text_without_digits_is_untouched():
    text = "Кино, «Звезда по имени Солнце», восемьдесят девятый год."
    assert N.normalize(text) == text
